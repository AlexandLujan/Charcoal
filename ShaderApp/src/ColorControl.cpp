bool color_in_map(string cName)
{
	return (colorMap.find(cName) != colorMap.end());
}

XMFLOAT4 FindColor(string cName)
{
	if (!cName.empty())
	{
		transform(cName.begin(), cName.end(), cName.begin(), ::toupper); // change to uppercase for key comparison
		if (color_in_map(cName))
		{
			uint32_t rgb = colorMap.at(cName);
			return RGB2FRGB(rgb);
		}
	}
	return RGB2FRGB(0x00A5A5A5);
}

std::mt19937 ColorControl::gen{ static_cast<unsigned int>(std::time(0)) }; // Seed with time
std::uniform_int_distribution<> ColorControl::colordist(0, (UINT)colorMap.size() - 1);
std::uniform_int_distribution<> ColorControl::framedist(2, 6);

std::string RandomColor()
{
	UINT randomColor = ColorControl::colordist(ColorControl::gen);
	auto random_it = colorMap.begin();
	std::advance(random_it, randomColor);
	return random_it->first;
}
